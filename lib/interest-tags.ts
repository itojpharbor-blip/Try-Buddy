export function relatedTagsFor(opportunity:Opportunity){
  const source=[opportunity.name,opportunity.summary,...opportunity.tags].join(' ');
  const matches=curatedTags.filter(tag=>tagRules[tag]?.test(source));
  const base=opportunity.category==='コンテスト'?['コンテスト']:opportunity.category==='ボランティア'?['ボランティア']:['国際交流'];
  if(opportunity.category==='留学・国際交流'&&!matches.includes('留学')&&/留学|海外/.test(source))base.push('留学');
  return [...new Set([...base,...matches])].slice(0,12);
}

export function cleanTag(value:unknown){
  if(typeof value!=='string')return '';
  const tag=value.normalize('NFKC').trim().replace(/\s+/g,' ');
  return tag.length>=2&&tag.length<=24&&!/[<>\r\n\t]/.test(tag)?tag:'';
}
